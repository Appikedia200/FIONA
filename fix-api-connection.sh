#!/bin/bash
# Fix Frontend → Backend Connection
# Run this script on your VPS as root

set -e

echo "🔧 FIONA API Connection Fix Script"
echo "===================================="
echo ""

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

# Check if running as root
if [ "$EUID" -ne 0 ]; then 
  echo -e "${RED}❌ Please run as root (sudo bash fix-api-connection.sh)${NC}"
  exit 1
fi

echo -e "${YELLOW}Step 1: Checking backend status...${NC}"
su - fiona -c "pm2 status" || {
  echo -e "${RED}❌ Backend not running!${NC}"
  echo "Start it with: su - fiona -c 'cd /var/www/fiona/backend && pm2 start ecosystem.config.js'"
  exit 1
}

echo -e "${GREEN}✅ Backend is running${NC}"
echo ""

echo -e "${YELLOW}Step 2: Testing backend health...${NC}"
if curl -s http://localhost:8000/health | grep -q "healthy"; then
  echo -e "${GREEN}✅ Backend responds to health check${NC}"
else
  echo -e "${RED}❌ Backend not responding!${NC}"
  echo "Check logs: su - fiona -c 'pm2 logs fiona-backend --lines 50'"
  exit 1
fi
echo ""

echo -e "${YELLOW}Step 3: Creating Nginx config for api.fioona.org...${NC}"

# Create main panel config (fioona.org)
cat > /etc/nginx/sites-available/fioona.org << 'EOF'
# Web Panel - fioona.org
server {
    listen 80;
    listen [::]:80;
    server_name fioona.org www.fioona.org;
    
    # Let's Encrypt challenge
    location /.well-known/acme-challenge/ {
        root /var/www/html;
    }
    
    # Redirect to HTTPS
    location / {
        return 301 https://$host$request_uri;
    }
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name fioona.org www.fioona.org;
    
    # SSL certificates (will be auto-generated by certbot)
    ssl_certificate /etc/letsencrypt/live/fioona.org/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/fioona.org/privkey.pem;
    
    # SSL configuration
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_prefer_server_ciphers on;
    ssl_session_cache shared:SSL:10m;
    ssl_session_timeout 10m;
    
    # Security headers
    add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;
    add_header X-Frame-Options "SAMEORIGIN" always;
    add_header X-Content-Type-Options "nosniff" always;
    
    # Hide Nginx version
    server_tokens off;
    
    # Root directory (for Next.js static build)
    root /var/www/fiona/web-panel/out;
    index index.html;
    
    # Next.js static files
    location / {
        try_files $uri $uri.html $uri/ =404;
    }
    
    # Static assets with caching
    location /_next/static/ {
        alias /var/www/fiona/web-panel/out/_next/static/;
        expires 1y;
        add_header Cache-Control "public, immutable";
    }
}
EOF

# Create API config (api.fioona.org)
cat > /etc/nginx/sites-available/api.fioona.org << 'EOF'
# API Backend - api.fioona.org
server {
    listen 80;
    listen [::]:80;
    server_name api.fioona.org;
    
    # Let's Encrypt challenge
    location /.well-known/acme-challenge/ {
        root /var/www/html;
    }
    
    # Redirect to HTTPS
    location / {
        return 301 https://$host$request_uri;
    }
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name api.fioona.org;
    
    # SSL certificates (will be auto-generated by certbot)
    ssl_certificate /etc/letsencrypt/live/api.fioona.org/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/api.fioona.org/privkey.pem;
    
    # SSL configuration
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers HIGH:!aNULL:!MD5;
    ssl_prefer_server_ciphers on;
    ssl_session_cache shared:SSL:10m;
    ssl_session_timeout 10m;
    
    # Security headers
    add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;
    
    # Hide Nginx version
    server_tokens off;
    
    # Proxy to backend
    location / {
        proxy_pass http://localhost:8000;
        proxy_http_version 1.1;
        
        # WebSocket support
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection 'upgrade';
        
        # Headers
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        
        # CORS headers (backend handles these, but Nginx passes them through)
        proxy_hide_header Access-Control-Allow-Origin;
        
        # Timeouts
        proxy_connect_timeout 60s;
        proxy_send_timeout 60s;
        proxy_read_timeout 60s;
        
        # Buffering
        proxy_buffering off;
        proxy_cache_bypass $http_upgrade;
    }
    
    # Health check endpoint (no logging)
    location /health {
        proxy_pass http://localhost:8000/health;
        access_log off;
    }
}
EOF

echo -e "${GREEN}✅ Nginx configs created${NC}"
echo ""

echo -e "${YELLOW}Step 4: Enabling sites...${NC}"

# Remove default site
rm -f /etc/nginx/sites-enabled/default
rm -f /etc/nginx/sites-enabled/fiona

# Enable new sites
ln -sf /etc/nginx/sites-available/fioona.org /etc/nginx/sites-enabled/
ln -sf /etc/nginx/sites-available/api.fioona.org /etc/nginx/sites-enabled/

echo -e "${GREEN}✅ Sites enabled${NC}"
echo ""

echo -e "${YELLOW}Step 5: Testing Nginx configuration...${NC}"
if nginx -t; then
  echo -e "${GREEN}✅ Nginx config is valid${NC}"
else
  echo -e "${RED}❌ Nginx config has errors!${NC}"
  exit 1
fi
echo ""

echo -e "${YELLOW}Step 6: Reloading Nginx...${NC}"
systemctl reload nginx
echo -e "${GREEN}✅ Nginx reloaded${NC}"
echo ""

echo -e "${YELLOW}Step 7: Checking DNS records...${NC}"
echo ""
echo "Make sure you have these DNS records in Cloudflare:"
echo "  A    fioona.org        → 144.172.94.13"
echo "  A    www.fioona.org    → 144.172.94.13"
echo "  A    api.fioona.org    → 144.172.94.13"
echo ""

# Check if domains resolve
echo "Checking DNS resolution..."
for domain in fioona.org api.fioona.org; do
  IP=$(dig +short $domain | tail -n1)
  if [ "$IP" = "144.172.94.13" ]; then
    echo -e "  ${GREEN}✅ $domain → $IP${NC}"
  else
    echo -e "  ${YELLOW}⚠️  $domain → ${IP:-NOT_FOUND} (expected: 144.172.94.13)${NC}"
  fi
done
echo ""

echo -e "${YELLOW}Step 8: Getting SSL certificates...${NC}"
echo ""
echo "⚠️  IMPORTANT: Before running this, make sure:"
echo "  1. DNS records are pointing to this server"
echo "  2. Firewall allows ports 80 and 443"
echo "  3. No other service is using ports 80/443"
echo ""
read -p "Ready to get SSL certificates? (y/N): " -n 1 -r
echo ""

if [[ $REPLY =~ ^[Yy]$ ]]; then
  echo "Getting SSL certificate for api.fioona.org..."
  certbot --nginx -d api.fioona.org --non-interactive --agree-tos --email admin@fioona.org || {
    echo -e "${RED}❌ Failed to get SSL certificate for api.fioona.org${NC}"
    echo "This might be because:"
    echo "  - DNS not propagated yet (wait 5-10 minutes and try again)"
    echo "  - Port 80 not accessible from internet"
    echo "  - Domain not pointing to this server"
    echo ""
    echo "You can manually run later: certbot --nginx -d api.fioona.org"
  }
  
  echo ""
  echo "Getting SSL certificate for fioona.org..."
  certbot --nginx -d fioona.org -d www.fioona.org --non-interactive --agree-tos --email admin@fioona.org || {
    echo -e "${RED}❌ Failed to get SSL certificate for fioona.org${NC}"
    echo "You can manually run later: certbot --nginx -d fioona.org -d www.fioona.org"
  }
  
  echo ""
  systemctl reload nginx
else
  echo -e "${YELLOW}⚠️  Skipping SSL certificate generation${NC}"
  echo "Run manually when DNS is ready:"
  echo "  sudo certbot --nginx -d api.fioona.org"
  echo "  sudo certbot --nginx -d fioona.org -d www.fioona.org"
fi

echo ""
echo -e "${GREEN}========================================${NC}"
echo -e "${GREEN}✅ API Connection Fix Complete!${NC}"
echo -e "${GREEN}========================================${NC}"
echo ""
echo "Next steps:"
echo "  1. Update your web panel .env.local:"
echo "     NEXT_PUBLIC_API_URL=https://api.fioona.org"
echo ""
echo "  2. Rebuild and deploy web panel"
echo ""
echo "  3. Test the connection:"
echo "     curl https://api.fioona.org/health"
echo ""
echo "  4. Check backend logs if issues:"
echo "     su - fiona -c 'pm2 logs fiona-backend --lines 50'"
echo ""
echo "  5. Monitor Nginx logs:"
echo "     tail -f /var/log/nginx/error.log"
echo ""
